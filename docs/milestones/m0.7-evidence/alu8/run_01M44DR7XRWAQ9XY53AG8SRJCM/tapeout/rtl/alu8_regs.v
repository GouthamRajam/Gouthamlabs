// -----------------------------------------------------------------------------
// Module : alu8_regs
// Design : alu8 (S2S Phase 0, sky130A / sky130_fd_sc_hd)
// Purpose: Output register bank of the 8-bit ALU. Registers the combinational
//          results from alu8_core: W-bit result plus 4 flags (Z, C, V, N),
//          exactly W + 4 = 12 flops for W = 8. No FSM, no other logic.
// Requirements implemented:
//   REQ-006  result holds on CMP (load enable res_we = 0); flags still update
//   REQ-009  all outputs registered, 1-cycle latency
//   REQ-010  synchronous active-low reset clears result and all flags to 0
//   REQ-011  every state element is reset by rst_n
//   REQ-013  rst_n = 0 has priority over all operations
//   REQ-015  one operation per clock, no wait states
//   REQ-016  exactly 12 flops (8 result + 4 flags) for W = 8
// Assumptions:
//   - res_we is generated by alu8_core as (op != CMP).
//   - Single clock domain clk; all inputs are synchronous to clk (REQ-014),
//     so no synchronizers are needed.
//   - Reset value of flag_z is 0 (spec DEFAULT - needs G1 review).
// -----------------------------------------------------------------------------
module alu8_regs #(
    parameter integer W = 8                 // datapath width
) (
    input  wire         clk,
    input  wire         rst_n,              // synchronous, active low
    input  wire [W-1:0] res_next,
    input  wire         z_next,
    input  wire         c_next,
    input  wire         v_next,
    input  wire         n_next,
    input  wire         res_we,             // 1: load result, 0: hold (CMP)
    output wire [W-1:0] result,
    output wire         flag_z,
    output wire         flag_c,
    output wire         flag_v,
    output wire         flag_n
);

    // Reset values (REQ-010)
    localparam [W-1:0] RESULT_RST = {W{1'b0}};
    localparam         FLAG_RST   = 1'b0;

    // State elements: W result flops + 4 flag flops (REQ-016)
    reg [W-1:0] result_q;
    reg         flag_z_q;
    reg         flag_c_q;
    reg         flag_v_q;
    reg         flag_n_q;

    always @(posedge clk) begin
        if (!rst_n) begin
            // REQ-010 REQ-011 REQ-013: synchronous reset, priority over loads
            result_q <= RESULT_RST;
            flag_z_q <= FLAG_RST;
            flag_c_q <= FLAG_RST;
            flag_v_q <= FLAG_RST;
            flag_n_q <= FLAG_RST;
        end else begin
            // REQ-006: result loads only when res_we = 1 (holds on CMP)
            if (res_we) begin
                result_q <= res_next;       // REQ-009 REQ-015
            end
            // REQ-009 REQ-015: flags load every cycle (including CMP, REQ-006)
            flag_z_q <= z_next;
            flag_c_q <= c_next;
            flag_v_q <= v_next;
            flag_n_q <= n_next;
        end
    end

    // REQ-009: outputs driven directly from registers
    assign result = result_q;
    assign flag_z = flag_z_q;
    assign flag_c = flag_c_q;
    assign flag_v = flag_v_q;
    assign flag_n = flag_n_q;

endmodule
