"""Tape-out Readiness Report (MASTER_SPEC Part 22), computed from the checks that actually ran.

The Phase 0 gate is the hard checks (pass/fail: DRC, LVS, antenna, timing at all corners, equivalence)
plus a scope label on every check. The Baseline A/B percentages are derived figures, printed with the
partial-credit values they depend on; they are not the gate (decision 2026-10-06).

Each check gets a result: clean (1), partial (config/readiness.yaml `partial_other`), deferred, not run
or failed (0). Each baseline caps what a check can earn (Part 22.3 table): Full = the result, Partial =
at most that check's partial credit (`partial_credit.ir_em`, `partial_credit.dft`, else `partial_other`),
No = 0, n/a = not counted toward that baseline. DFT earns nothing unless a fault coverage was measured.
Score = sum(weight x earned) / sum(applicable weights). Never rounds up: one decimal, floored.
"""
from __future__ import annotations

import json
import math
import re
from pathlib import Path

from s2s.config import _load

# Part 22.3: (counts toward A, counts toward B); "full" | "partial" | "no" | None (n/a)
CAPS = {
    "functional_sim": ("full", "full"),
    "coverage": ("full", "full"),
    "formal_equiv": ("full", "full"),
    "drc": ("full", "partial"),
    "lvs": ("full", "partial"),
    "antenna": ("full", "full"),
    "density": ("full", "full"),
    "sta_setup_hold": ("full", "partial"),
    "power": ("full", "partial"),
    "ir_em_static": ("partial", "partial"),
    "dft_atpg": ("partial", "no"),
    "signal_integrity": (None, "no"),
    "reliability": (None, "no"),
    "foundry_signoff": (None, "no"),
    "gds_integrity_repro": ("full", "full"),
}
PARTIAL_KEY = {"ir_em_static": "ir_em", "dft_atpg": "dft"}  # checks with their own partial credit
LABEL = {
    "functional_sim": "Functional sim (RTL + gate-level)", "coverage": "Coverage (line, toggle, functional)",
    "formal_equiv": "Formal properties + RTL/netlist equivalence", "drc": "DRC", "lvs": "LVS",
    "antenna": "Antenna", "density": "Density / fill", "sta_setup_hold": "Setup + hold STA, all PDK corners",
    "power": "Power estimate", "ir_em_static": "IR drop / EM (static)", "dft_atpg": "DFT scan + ATPG fault coverage",
    "signal_integrity": "Signal integrity / crosstalk", "reliability": "Reliability (aging, ESD, latch-up)",
    "foundry_signoff": "Foundry-certified signoff (Calibre-class)",
    "gds_integrity_repro": "GDS integrity + reproducibility",
}
DFT_DEFERRED = "deferred - not measured, 0 fault coverage; achievable with open tools in Phase 1"
IR_EM_LIMITED = "measured: passed, tool-limited"
EXCLUDED_A = "excluded from Baseline A - open tools structurally cannot do this (Phase 1+)"
NO_EDIT_CHECK = ("artifacts are machine-generated by the flow; no automated edit-detection check exists yet "
                 "(hash/provenance check is in the Phase 1 plan)")
CLOSE = {  # what would close each gap, and when
    "drc": "foundry-certified DRC deck (Phase 1, commercial tools)",
    "lvs": "foundry-certified LVS deck (Phase 1, commercial tools)",
    "sta_setup_hold": "OCV/AOCV and SI-aware timing (Phase 1, commercial STA)",
    "power": "vector-based power with silicon-correlated models (Phase 1)",
    "ir_em_static": "real static IR + EM analysis with OpenROAD (Phase 1); dynamic IR/EM with a package model "
                    "needs commercial tools",
    "dft_atpg": "scan insertion + ATPG fault coverage with open tools: OpenROAD DFT + Fault (Phase 1)",
    "signal_integrity": "crosstalk/SI analysis (Phase 1, commercial tools)",
    "reliability": "aging, ESD and latch-up analysis (Phase 1-2)",
    "foundry_signoff": "Calibre-class foundry signoff (Phase 1)",
}
ASSUMPTIONS = """ASSUMPTIONS
- PDK: SkyWater SKY130 (open), library sky130_fd_sc_hd. Not a commercial foundry PDK.
- DRC/LVS: open-source Magic, KLayout and Netgen decks. A foundry's own certified
  decks (e.g. Calibre) were not run and may differ.
- Timing: OpenSTA at the PDK's typical/slow/fast corners. No on-chip variation
  (OCV/AOCV), no SI-aware timing. Clock target as stated per design.
- Power/IR: estimated at 20% switching activity unless simulation activity was used;
  IR/EM analysis limited to what the open flow supports.
- DFT: deferred in Phase 0 (plan only). Not measured: 0 fault coverage, earns no
  credit. Achievable with open tools (OpenROAD DFT + Fault) in Phase 1.
- Not assessed (out of open-flow scope): signal integrity/crosstalk, aging/ESD/
  latch-up reliability, foundry-certified signoff.
- No physical silicon was manufactured or tested. All results are pre-silicon,
  from simulation and layout tools.
- Baseline A = open SKY130 shuttle requirements. Baseline B = commercial production
  tape-out on a real foundry PDK."""


def _floor1(x: float) -> float:
    return math.floor(x * 10 + 1e-9) / 10


def _scope(key: str, result: str) -> str:
    if key == "dft_atpg" and result == "deferred":
        return DFT_DEFERRED
    if CAPS[key][0] is None:
        return EXCLUDED_A
    if result == "clean":
        return IR_EM_LIMITED if key == "ir_em_static" else "measured: passed"
    return {"partial": "measured: partly passed", "failed": "measured: FAILED", "not run": "not run"}[result]


def score(results: dict[str, dict], hard: dict | None = None) -> dict:
    """results: check -> {"result": "clean"|"partial"|"not run"|"failed", "tool": str, "evidence": str,
    "note": str, "fault_coverage_pct": float (DFT only, when measured)}. Missing checks count as not run.
    hard: the hard-check table from hard_checks(); it is the gate, the percentages are derived."""
    cfg = _load("readiness.yaml", "S2S_READINESS_CONFIG")
    weights, pc = cfg["weights"], cfg["partial_credit"]
    other = float(cfg["partial_other"])
    partial = {"dft": float(pc["dft"]), "ir_em": float(pc["ir_em"]), "other": other}
    value = {"clean": 1.0, "partial": other, "deferred": 0.0, "not run": 0.0, "failed": 0.0}
    rows, num = [], {"A": 0.0, "B": 0.0}
    den = {"A": 0.0, "B": 0.0}
    for key, w in weights.items():
        r = dict(results.get(key, {"result": "not run", "tool": "-", "evidence": "", "note": "not run"}))
        if key == "dft_atpg" and not isinstance(r.get("fault_coverage_pct"), (int, float)):
            r["result"] = "deferred"  # a plan is not a measurement: no fault coverage, no credit
        v = value[r["result"]]
        row = {"check": key, "label": LABEL[key], "weight": w, **r, "scope": _scope(key, r["result"])}
        for i, base in enumerate(("A", "B")):
            cap = CAPS[key][i]
            if cap is None:
                row[f"earned_{base}"] = None
                continue
            earned = 0.0 if cap == "no" else min(v, 1.0 if cap == "full" else partial[PARTIAL_KEY.get(key, "other")])
            row[f"earned_{base}"] = round(w * earned, 4)
            num[base] += w * earned
            den[base] += w
        rows.append(row)
    gaps = []
    for row in rows:
        full = all(row[f"earned_{b}"] is None or row[f"earned_{b}"] >= row["weight"] for b in ("A", "B"))
        if not full:
            gaps.append({"check": row["label"], "result": row["result"], "scope": row["scope"],
                         "closes_with": CLOSE.get(row["check"], "fix the failing check and re-run (this phase)")
                         if row["result"] in ("clean", "partial", "deferred") or CAPS[row["check"]][0] is None
                         else "fix and re-run the check (this phase)"})
    return {"hard_checks": hard, "baseline_A_pct": _floor1(100 * num["A"] / den["A"]),
            "baseline_B_pct": _floor1(100 * num["B"] / den["B"]), "derived": True, "partial_credit": partial,
            "earned_A_total": round(num["A"], 4), "earned_B_total": round(num["B"], 4),
            "weights_A_total": den["A"], "weights_B_total": den["B"], "weights_total": float(sum(weights.values())),
            "rows": rows, "gaps": gaps, "assumptions": ASSUMPTIONS}


def _json(p: Path) -> dict:
    try:
        return json.loads(p.read_text())
    except (OSError, ValueError):
        return {}


def hard_checks(passed: dict[str, bool], evidence: dict[str, str], reports: Path) -> dict:
    """The Phase 0 gate table. passed/evidence keys: drc, lvs, antenna, timing, equivalence (from the checks
    that ran). Details come from reports/pv_signoff.json and reports/sta_signoff.json. A timing pass that
    relies on the clock-net fanout rule is marked conditional, with what a flat SDC limit would do."""
    pv, sta = _json(reports / "pv_signoff.json"), _json(reports / "sta_signoff.json")
    corners = sta.get("corners") or {}
    det = {"drc": "", "lvs": "", "antenna": "", "timing": "", "equivalence": ""}
    if pv:
        det["drc"] = (f"Magic {pv.get('magic_drc', {}).get('violations')}, "
                      f"KLayout {pv.get('klayout_drc', {}).get('violations')} violations on the final GDS")
        lv = pv.get("lvs", {})
        c = lv.get("counts", {})
        det["lvs"] = (f"{lv.get('verdict')} ({c.get('devices', {}).get('layout')} devices, "
                      f"{c.get('nets', {}).get('layout')} nets)")
        a = pv.get("antenna", {})
        det["antenna"] = (f"{a.get('net_violations')} net / {a.get('pin_violations')} pin violations "
                          f"({a.get('nets_checked')} nets checked)")
    conditions, allowed = [], {}
    if corners:
        ws = min((v["setup_ws_ns"], k) for k, v in corners.items())
        wh = min((v["hold_ws_ns"], k) for k, v in corners.items())
        tns = sum(v["setup_tns_ns"] + v["hold_tns_ns"] for v in corners.values())
        det["timing"] = (f"{sum(1 for v in corners.values() if v.get('passed'))}/{len(corners)} corners; worst setup "
                         f"{ws[0]:+g} ns ({ws[1]}), worst hold {wh[0]:+g} ns ({wh[1]}); TNS {tns:g}")
        for v in corners.values():
            for e in v.get("clock_rule_allowed") or []:
                allowed[e["pin"]] = e
    if allowed:
        es = list(allowed.values())
        m = re.search(r"limit (\d+(?:\.\d+)?)", es[0].get("rule", ""))
        conditions.append(
            f"CONDITIONAL PASS: timing/DRV passes only under the approved clock-net max-fanout limit of "
            f"{m.group(1) if m else '?'} (config/signoff.yaml cts.clock_max_fanout). {len(es)} clock-tree buffer "
            f"outputs have fanout {min(e['value'] for e in es):g}-{max(e['value'] for e in es):g}, above the SDC "
            f"limit of {max(e['limit'] for e in es):g}. Under a flat SDC max-fanout limit of "
            f"{max(e['limit'] for e in es):g} this design FAILS.")
    names = {"drc": "DRC = 0 (Magic + KLayout, final GDS)", "lvs": "LVS match (Netgen, final GDS)",
             "antenna": "Antenna clean", "timing": "Timing met, all corners (setup, hold, DRV)",
             "equivalence": "Equivalence RTL vs final netlist proven"}
    items = []
    for k, name in names.items():
        ok = bool(passed.get(k, False))
        st = "PASS" if ok else "FAIL"
        if ok and k == "timing" and allowed:
            st = "PASS (conditional)"
        items.append({"check": name, "status": st, "passed": ok, "detail": det[k], "evidence": evidence.get(k, "")})
    items.append({"check": "No human edits to artifacts", "status": "NOT CHECKED", "passed": None,
                  "detail": NO_EDIT_CHECK, "evidence": ""})
    n_ok = sum(1 for i in items if i["passed"])
    verdict = "PASS" if n_ok == len(names) else "FAIL"
    if verdict == "PASS" and conditions:
        verdict = "CONDITIONAL PASS"
    return {"verdict": verdict, "passed": n_ok, "of": len(names), "items": items, "conditions": conditions}


def markdown(design: str, rep: dict, links: dict[str, str]) -> str:
    hard, pc = rep.get("hard_checks"), rep["partial_credit"]
    out = [f"# Tape-out Readiness Report: {design}", "", "## Phase 0 gate: hard checks (pass/fail)", ""]
    if hard:
        out += [f"**Hard checks: {hard['verdict']} ({hard['passed']} of {hard['of']})**", ""]
        out += [f"> **{c}**" for c in hard["conditions"]] + ([""] if hard["conditions"] else [])
        out += ["| Hard check | Result | Detail | Evidence |", "|---|---|---|---|"]
        out += [f"| {i['check']} | {i['status']} | {i['detail']} | {i['evidence']} |" for i in hard["items"]]
    else:
        out += ["Hard checks: not supplied to this report."]
    out += ["", "Pre-silicon: no number here proves working silicon, only that the design passes the checks that were run.",
            "", "## Derived score (not the gate)", "",
            f"Baseline A (open shuttle): {rep['baseline_A_pct']:.1f}% · Baseline B (commercial production): "
            f"{rep['baseline_B_pct']:.1f}% - derived, with partial credit **dft={pc['dft']:g} / ir_em={pc['ir_em']:g}** "
            f"(Baseline B's other Partial caps: {pc['other']:g}).", "",
            f"Score = earned / applicable total. A = {rep['earned_A_total']:g} / {rep['weights_A_total']:g}; "
            f"B = {rep['earned_B_total']:g} / {rep['weights_B_total']:g}. The weights total "
            f"{rep['weights_total']:g} (not 100). A excludes signal integrity, reliability and foundry signoff "
            "(open tools structurally cannot do them); DFT stays in A at 0 (open tools can do it; not done yet). "
            "Floored to one decimal, never rounded up.",
            "", "## Rubric and scope labels", "",
            "| Check | Weight | Scope label | Result | Earned A | Earned B | Tool (version) | Evidence |",
            "|---|---|---|---|---|---|---|---|"]
    for r in rep["rows"]:
        a = "n/a" if r["earned_A"] is None else f"{r['earned_A']:g}"
        out.append(f"| {r['label']} | {r['weight']} | {r['scope']} | {r['result']}"
                   f"{' - ' + r['note'] if r.get('note') else ''} | {a} | {r['earned_B']:g} | {r['tool']} | "
                   f"{r.get('evidence', '')} |")
    out += ["", "## Gaps", ""]
    out += [f"- **{g['check']}** ({g['scope']}): closes with {g['closes_with']}" for g in rep["gaps"]] or ["- none"]
    out += ["", "## Assumptions", "", "```", rep["assumptions"], "```", "", "## Evidence", ""]
    out += [f"- {k}: `{v}`" for k, v in links.items()]
    return "\n".join(out) + "\n"
