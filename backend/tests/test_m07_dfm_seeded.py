"""M0.7 acceptance 3: Fabian's DFM screen detects seeded DFM issues in a test layout (live KLayout).

The test layout is generated by KLayout itself (SKY130 layer numbers as the PDK deck defines them).
It carries one seeded issue per check, each far from the others, plus a clean control wire that
must NOT be flagged:
  met2  two 0.14 um lines, 30 um long, 0.14 um apart          -> long parallel run (+ near-min space)
  met3  a lone 0.30 um x 10 um line                           -> isolated narrow line
  met1  a wire ending 0.14 um from a crossing wire            -> line end near limit
  met4  an 18 x 18 um solid block                              -> window density above the PDK max
  via   one 0.15 um cut in a 1.2 x 0.5 um met1/met2 overlap    -> single via where a second cut fits
  met2  a 0.5 um wide control wire with 5 um clearance        -> no item
"""
from __future__ import annotations

import os

import pytest
import yaml

from s2s.physical import dfm
from s2s.tools import runner

pytestmark = pytest.mark.eda

GEN = r'''
import pya
ly = pya.Layout()
ly.dbu = 0.001
top = ly.create_cell("seeded")
def box(l, d, x1, y1, x2, y2):
    top.shapes(ly.layer(l, d)).insert(pya.Box(int(x1 * 1000), int(y1 * 1000), int(x2 * 1000), int(y2 * 1000)))
box(235, 4, 0, 0, 200, 200)                       # prBoundary
box(69, 20, 10, 10, 40, 10.14)                    # met2 parallel pair, 0.14 apart, 30 um
box(69, 20, 10, 10.28, 40, 10.42)
box(70, 20, 100, 100, 100.30, 110)                # met3 isolated narrow line
box(68, 20, 10, 60, 15, 60.14)                    # met1 wire ending at x=15 ...
box(68, 20, 15.14, 57, 15.28, 63)                 # ... 0.14 um from a crossing wire
box(71, 20, 141, 141, 159, 159)                   # met4 dense block (window 140..160 = 81%)
box(68, 20, 60, 140, 61.2, 140.5)                 # met1/met2 overlap 1.2 x 0.5 with one via
box(69, 20, 60, 140, 61.2, 140.5)
box(68, 44, 60.06, 140.175, 60.21, 140.325)
box(69, 20, 150, 20, 160, 20.5)                   # clean control wire
ly.write(out)
print("S2S_GEN_DONE")
'''


@pytest.fixture(scope="module", autouse=True)
def eda_available():
    try:
        runner.image_id()
    except runner.EdaUnavailable as e:
        if os.environ.get("S2S_REQUIRE_EDA") == "1":
            pytest.fail(f"S2S_REQUIRE_EDA=1 but the EDA environment is unavailable: {e}")
        pytest.skip(f"EDA environment unavailable: {e}")


def test_seeded_dfm_issues_are_detected(tmp_path):
    from s2s.config import REPO_ROOT
    gen = tmp_path / "gen.py"
    gen.write_text(GEN)
    gds = tmp_path / "seeded.gds"
    rec = runner.run(["klayout", "-b", "-r", str(gen), "-rd", f"out={gds}"], tmp_path, tmp_path / "gen.log", "klayout", 300)
    assert rec.exit_code == 0 and gds.exists(), rec.log_path.read_text()
    policy = yaml.safe_load((REPO_ROOT / "config" / "signoff.yaml").read_text())["dfm"]
    data = dfm.run_dfm_layout(gds, "seeded", tmp_path, policy, name="dfm_seeded")
    found = dfm.items(data, [], policy)
    by = {(i["check"], i["title"].split(":")[0]): i for i in found}

    assert data["layers"]["met2"]["long_parallel_runs"] >= 1
    assert data["layers"]["met2"]["long_parallel_run_list"][0]["length_um"] >= 29.9
    assert ("parallel_run", "met2") in by and by[("parallel_run", "met2")]["severity"] == "medium"
    assert data["layers"]["met3"]["isolated_narrow_lines"] == 1
    assert ("isolated_line", "met3") in by
    assert data["layers"]["met1"]["line_end_near_limit"] >= 1
    assert ("line_end", "met1") in by
    assert data["layers"]["met4"]["density_over_max"], data["layers"]["met4"]["density_window_max"]
    assert by[("density", "met4")]["severity"] == "high"
    assert data["vias"]["via"]["redundant_via_fits"] == 1
    assert ("single_via", "via") in by
    # PDK limits came from the decks, not from this code
    assert data["pdk_rules"]["met1"]["min_width"] == 0.14 and data["pdk_rules"]["met4"]["max_density"] == 0.6
    # the clean control wire (x 150..160, y 20) is in no hotspot list
    for i in found:
        for loc in i["locations"]:
            if isinstance(loc, list):
                assert not (loc[0] >= 149 and loc[2] <= 161 and 19 <= loc[1] <= 21), (i["title"], loc)


def test_antenna_margin_parser():
    text = """Net: n1
  Pin:   u1/A (sky130_fd_sc_hd__inv_1)
    Layer: met1
      Partial area ratio:  320.00
      Required ratio:  400.00 (Side area)
      Cumulative area ratio:  10.0
      Required ratio:    0.00 (Cumulative side area)

Net: n2
  Pin:   u2/A (sky130_fd_sc_hd__inv_1)
    Layer: met2
      Partial area ratio:  410.00
      Required ratio:  400.00 (Side area)
"""
    worst = dfm.parse_antenna_verbose(text)
    assert [w["net"] for w in worst] == ["n2", "n1"]
    assert worst[0]["pct_of_limit"] == 102.5 and worst[1]["pct_of_limit"] == 80.0
    items = dfm.items({"layers": {}, "vias": {}}, worst, {"antenna_margin_flag_pct": 80, "density_near_max_pct": 90,
                                                         "long_parallel_run_um": 10, "near_limit_pct": 5})
    assert [(i["severity"], i["count"]) for i in items] == [("high", 1), ("medium", 1)]
